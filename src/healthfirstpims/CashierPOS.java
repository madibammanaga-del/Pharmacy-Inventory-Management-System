    private void tblCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tblCartActionPerformed
        String selectedMedicine = (String) cmbMedicine.getSelectedItem();
        String quantityText = txtQuantity.getText().trim();

if (selectedMedicine == null) {
    JOptionPane.showMessageDialog(this,
            "Please select a medicine.");
    return;
}

if (quantityText.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please enter the quantity.");
    return;
}

try {

    int quantity = Integer.parseInt(quantityText);

    if (quantity <= 0) {
        JOptionPane.showMessageDialog(this,
                "Quantity must be greater than 0.");
        return;
    }

    int medicineId = Integer.parseInt(
            selectedMedicine.split(" - ")[0]
    );

    Connection con = DatabaseConnection.getConnection();

    String sql = "SELECT name, price, quantity_in_stock "
               + "FROM medicines WHERE medicine_id = ?";

    PreparedStatement pst = con.prepareStatement(sql);
    pst.setInt(1, medicineId);

    ResultSet rs = pst.executeQuery();

    if (rs.next()) {

        String medicineName = rs.getString("name");
        double price = rs.getDouble("price");
        int stock = rs.getInt("quantity_in_stock");

        if (quantity > stock) {
            JOptionPane.showMessageDialog(this,
                    "Not enough stock available.\n"
                    + "Available stock: " + stock);

            rs.close();
            pst.close();
            con.close();
            return;
        }

        double subtotal = price * quantity;

        DefaultTableModel model =
                (DefaultTableModel) tblCartTwo.getModel();

        model.addRow(new Object[]{
            medicineId,
            medicineName,
            quantity,
            price,
            subtotal
        });

        total += subtotal;

        lblTotal.setText(
                String.format("Total: R%.2f", total)
        );

        txtQuantity.setText("");
    }

    rs.close();
    pst.close();
    con.close();

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Please enter a valid number for quantity.",
            "Invalid Quantity",
            JOptionPane.ERROR_MESSAGE);

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Database error: " + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_tblCartActionPerformed

