    private void showBill(int saleId) {

    DefaultTableModel model =
            (DefaultTableModel) tblCartTwo.getModel();

    StringBuilder bill = new StringBuilder();

    bill.append("========================================\n");
    bill.append("          HEALTHFIRST PHARMACY\n");
    bill.append("             SALES RECEIPT\n");
    bill.append("========================================\n");
    bill.append("Sale ID: ").append(saleId).append("\n");
    bill.append("Cashier: ").append(loggedInUserName).append("\n");
    bill.append("========================================\n");
    bill.append("Medicine              Qty       Amount\n");
    bill.append("----------------------------------------\n");

    for (int i = 0; i < model.getRowCount(); i++) {

        String medicine =
                model.getValueAt(i, 1).toString();

        int quantity =
                Integer.parseInt(model.getValueAt(i, 2).toString());

        double subtotal =
                Double.parseDouble(model.getValueAt(i, 4).toString());

        bill.append(String.format(
                "%-20s %3d     R%8.2f%n",
                medicine,
                quantity,
                subtotal
        ));
    }

    bill.append("----------------------------------------\n");
    bill.append(String.format(
            "TOTAL:                         R%.2f%n",
            total
    ));
    bill.append("========================================\n");
    bill.append("       Thank you for your purchase!\n");
    bill.append("========================================");

    JOptionPane.showMessageDialog(
            this,
            bill.toString(),
            "HealthFirst Pharmacy - Bill",
            JOptionPane.INFORMATION_MESSAGE
    );
}
    
    private void btnCheckoutActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckoutActionPerformed
          if (tblCartTwo.getRowCount() == 0) {

        JOptionPane.showMessageDialog(this,
                "Cart is empty. Please add medicine first.");

        return;
    }

    Connection con = null;
    PreparedStatement salePst = null;
    PreparedStatement itemPst = null;
    PreparedStatement stockPst = null;
    ResultSet generatedKeys = null;

    try {

        con = DatabaseConnection.getConnection();

        // Start database transaction
        con.setAutoCommit(false);

        // 1. Create the sale
        String saleSql =
                "INSERT INTO sales (sale_date, total_amount, user_id) "
                + "VALUES (NOW(), ?, ?)";

        salePst = con.prepareStatement(
                saleSql,
                Statement.RETURN_GENERATED_KEYS
        );

        salePst.setDouble(1, total);
        salePst.setInt(2, loggedInUserId);

        salePst.executeUpdate();

        // Get the automatically generated sale_id
        generatedKeys = salePst.getGeneratedKeys();

        if (!generatedKeys.next()) {

            throw new Exception(
                    "Could not get the generated sale ID."
            );
        }

        int saleId = generatedKeys.getInt(1);

        // 2. Prepare sale item insert
        String itemSql =
                "INSERT INTO sale_items "
                + "(sale_id, medicine_id, quantity_sold, price_at_sale) "
                + "VALUES (?, ?, ?, ?)";

        itemPst = con.prepareStatement(itemSql);

        // 3. Prepare stock update
        String stockSql =
                "UPDATE medicines "
                + "SET quantity_in_stock = quantity_in_stock - ? "
                + "WHERE medicine_id = ? "
                + "AND quantity_in_stock >= ?";

        stockPst = con.prepareStatement(stockSql);

        DefaultTableModel model =
                (DefaultTableModel) tblCartTwo.getModel();

        // 4. Process every item in the cart
        for (int i = 0; i < model.getRowCount(); i++) {

            int medicineId = Integer.parseInt(
                    model.getValueAt(i, 0).toString()
            );

            int quantity = Integer.parseInt(
                    model.getValueAt(i, 2).toString()
            );

            double price = Double.parseDouble(
                    model.getValueAt(i, 3).toString()
            );

            // Insert sale item
            itemPst.setInt(1, saleId);
            itemPst.setInt(2, medicineId);
            itemPst.setInt(3, quantity);
            itemPst.setDouble(4, price);

            itemPst.executeUpdate();

            // Reduce stock
            stockPst.setInt(1, quantity);
            stockPst.setInt(2, medicineId);
            stockPst.setInt(3, quantity);

            int rowsUpdated = stockPst.executeUpdate();

            if (rowsUpdated != 1) {

                throw new Exception(
                        "Not enough stock available for medicine ID: "
                        + medicineId
                );
            }
        }

        // 5. Save everything
        con.commit();

        con.commit();
        
        //Show the full bill before clearing
        showBill(saleId);

        // 6. Clear the cart
        model.setRowCount(0);

        total = 0.0;

        lblTotal.setText("Total: R0.00");

        // 7. Refresh medicine list
        loadMedicines();

    } catch (Exception e) {

        try {

            if (con != null) {
                con.rollback();
            }

        } catch (Exception rollbackError) {

            JOptionPane.showMessageDialog(this,
                    "Rollback error: "
                    + rollbackError.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE);
        }

        JOptionPane.showMessageDialog(this,
                "Checkout failed: "
                + e.getMessage(),
                "Checkout Error",
                JOptionPane.ERROR_MESSAGE);

    } finally {

        try {
            if (generatedKeys != null) {
                generatedKeys.close();
            }

            if (salePst != null) {
                salePst.close();
            }

            if (itemPst != null) {
                itemPst.close();
            }

            if (stockPst != null) {
                stockPst.close();
            }

            if (con != null) {
                con.setAutoCommit(true);
                con.close();
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Error closing database connection: "
                    + e.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnCheckoutActionPerformed

